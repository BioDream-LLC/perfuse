package privacy

import (
	"bytes"
	"encoding/csv"
	"fmt"
	"sort"
	"strings"
	"time"
)

// The record of processing activities (Article 30, GDPR and UK GDPR), as far as this server knows it: who the controller
// is, where the data is kept, and for every channel what it receives, from where, and to whom it passes it. What only the
// controller knows (the purpose in law, the lawful basis, the categories of data subject) is left for them to fill in, and
// said so, rather than guessed.

// Controller is what the settings say about who is responsible.
type Controller struct {
	Name, DPO, Location string
	// Retention says how long each kind of record is kept, in words.
	Retention []RetentionRule
}

// RetentionRule is one category of data and how long it is kept.
type RetentionRule struct {
	Category string `json:"category"`
	Kept     string `json:"kept"`
	// Setting is the console setting that changes it, or "" when nothing here deletes it on a schedule.
	Setting string `json:"setting,omitempty"`
}

// Activity is one channel, as a processing activity.
type Activity struct {
	Channel     string   `json:"channel"`
	Description string   `json:"description"`
	Source      string   `json:"source"`
	Listen      string   `json:"listen,omitempty"`
	Recipients  []string `json:"recipients"`
	Hosts       []string `json:"hosts"`
	Enabled     bool     `json:"enabled"`
}

const fillIn = "(for the controller to fill in)"

// RegisterMarkdown writes the record as Markdown.
func RegisterMarkdown(c Controller, acts []Activity, now time.Time) []byte {
	var b bytes.Buffer
	or := func(s string) string {
		if strings.TrimSpace(s) == "" {
			return fillIn
		}
		return s
	}
	fmt.Fprintf(&b, "# Record of processing activities\n\nGenerated by Perfuse on %s from this server's configuration. "+
		"It describes what this server does with personal data; the purposes, lawful bases and the people the data is about are "+
		"the controller's to state.\n\n", now.UTC().Format("2 January 2006"))
	fmt.Fprintf(&b, "| | |\n|---|---|\n| Controller | %s |\n| Data protection officer | %s |\n| Where the data is kept | %s |\n"+
		"| Special category data | health data (Article 9): clinical messages and records |\n| Security measures | access by role, every "+
		"read of patient data audited, TLS where configured, second-person approval for erasure |\n\n", or(c.Name), or(c.DPO), or(c.Location))
	b.WriteString("## Retention\n\n| Data | Kept | Changed by |\n|---|---|---|\n")
	for _, r := range c.Retention {
		fmt.Fprintf(&b, "| %s | %s | %s |\n", r.Category, r.Kept, map[bool]string{true: "nothing on a schedule", false: r.Setting}[r.Setting == ""])
	}
	b.WriteString("\n## Processing activities (one per channel)\n\n| Channel | Purpose | Received from | Passed to | Hosts it sends to | On |\n|---|---|---|---|---|---|\n")
	sort.Slice(acts, func(i, j int) bool { return acts[i].Channel < acts[j].Channel })
	for _, a := range acts {
		from := a.Source
		if a.Listen != "" {
			from += " on " + a.Listen
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s |\n", md(a.Channel), md(or(a.Description)), md(from),
			md(strings.Join(a.Recipients, ", ")), md(strings.Join(a.Hosts, ", ")), map[bool]string{true: "yes", false: "no"}[a.Enabled])
	}
	b.WriteString("\nTransfers outside the UK or the EEA: check the hosts above against where each recipient keeps the data " + fillIn + ".\n")
	return b.Bytes()
}

func md(s string) string { return strings.NewReplacer("|", "\\|", "\n", " ").Replace(s) }

// RegisterCSV writes the activities as CSV, one row per channel, for a spreadsheet register.
func RegisterCSV(c Controller, acts []Activity) []byte {
	var b bytes.Buffer
	w := csv.NewWriter(&b)
	_ = w.Write([]string{"controller", "dpo", "location", "channel", "purpose", "source", "listen", "recipients", "hosts", "enabled",
		"lawful basis", "data subjects"})
	for _, a := range acts {
		row := []string{c.Name, c.DPO, c.Location, a.Channel, a.Description, a.Source, a.Listen, strings.Join(a.Recipients, "; "),
			strings.Join(a.Hosts, "; "), fmt.Sprint(a.Enabled), "", ""}
		for i, v := range row {
			row[i] = cell(v)
		}
		_ = w.Write(row)
	}
	w.Flush()
	return b.Bytes()
}

// cell keeps a spreadsheet from reading a value as a formula: a channel description beginning with = would otherwise run.
func cell(v string) string {
	if v != "" && strings.ContainsRune("=+-@\t\r", rune(v[0])) {
		return "'" + v
	}
	return v
}
